x = 3.14
y = 4
z = 5

# Round x to the nearest whole integer "round()"
round_result = round(x) 

# Absolute value of y "abs()" use for negative numbers.
abso_result = abs(y)

# Power function "pow()"
power_result = pow(4, 3) # 4 * 4 * 4

# Maximum value function "max()"
max_value_result = max(x, y, z)

# Minimum value function "min()"
min_value_result = min(x, y, z)

print(round_result)
print(abso_result)
print(power_result)
print(max_value_result)
print(min_value_result)