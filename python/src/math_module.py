import math # Math module or library

x = 9
y = 9.1
z = 9.9

result1 = math.sqrt(x) # Squareroot
result2 = math.ceil(y) # Always round a floating point number up
result3 = math.floor(z) # Always round a floating point number down

print(result1)
print(result2)
print(result3)
print(math.pi) # PI value
print(math.e) # Euler's number